"""向量索引：从零实现 HNSW 与 IVF-PQ，并给出可复现的检索质量/性能权衡数据。

零第三方依赖 —— **连 numpy 都不用**。这不是洁癖，是这个项目的题目本身：

* 内存占用是这个项目的核心指标之一，而用 ``array('f')``（紧凑的 C 浮点数组）
  而不是 ``list[float]`` 能直接把向量本体内存降到约 1/5；
  用了 numpy 之后这个量就变成"numpy 内部怎么存的"，反而看不见了。
* k-means、图构造、ADC 查表这些算法的**每一步**都直接暴露在代码里，
  可以被单测逐项验证（"第 3 次迭代后质心还在动吗"这种断言，在
  faiss 那种黑盒里根本写不出来）。
* 而性能的落差没有想象中大：距离计算用 ``math.sumprod``（Python 3.12+
  的 C 实现）展开成三次求和，实测比手写 Python 循环快约 2.9 倍。

诚实的边界写在 README 的「已知限制」里：纯 Python 的 k-means 在
大参数下会慢到不可用，所以默认参数偏小。这个项目要回答的是
**「这些算法为什么长这样」**，不是「谁能跑得最快」。
"""

